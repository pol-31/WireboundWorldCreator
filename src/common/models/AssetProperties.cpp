const AssetProperties& GetAssetDefaultProperties(const std::string& name) {
  static const AssetProperties default_prop{
      AssetProperties::Type::Static, AssetProperties::CollisionType::Cube,
      10.0f, false, false};
  static const AssetProperties default_tile_prop{
      AssetProperties::Type::Tile, AssetProperties::CollisionType::Cube, 10.0f,
      false, false};
  static const AssetProperties default_zone_prop{
      AssetProperties::Type::Zone, AssetProperties::CollisionType::Cube, 10.0f,
      false, false};
  static const AssetProperties default_portal_prop{
      AssetProperties::Type::Portal, AssetProperties::CollisionType::Cube,
      10.0f, false, false};
  static const AssetProperties default_npc_prop{
      AssetProperties::Type::Character, AssetProperties::CollisionType::Capsule,
      10.0f, false, false};
  auto it = gMeshNameToProperties.find(name);
  if (it == gMeshNameToProperties.end()) {
    if (name.rfind("m_tile", 0) == 0) return default_tile_prop;
    if (name.rfind("m_zone", 0) == 0) return default_zone_prop;
    if (name.rfind("m_portal", 0) == 0) return default_portal_prop;
    if (name.rfind("m_npc", 0) == 0) return default_npc_prop;
    return default_prop;
  }
  return it->second;
}
